# The injected collector runs in task images that may only have Python 3.5.
# Keep this script deliberately stdlib-only apart from the vendored coverage
# package.  ``coverage json`` reports only measured files; this finalizer asks
# coverage.py for static statement analysis of every requested target and
# fills an unimported target with ``executed_lines=[]`` and its full
# ``missing_lines`` universe.
COVERAGE_FINALIZE_SOURCE = (
    r'''
from __future__ import print_function

import json
import os

import coverage


def _normalise(value):
    return value.replace("\\\\", "/").lstrip("./")


def _lines(value):
    if not isinstance(value, (list, tuple, set)):
        return set()
    result = set()
    for item in value:
        try:
            result.add(int(item))
        except (TypeError, ValueError):
            pass
    return result


def _matches(candidate, absolute, relative):
    candidate = _normalise(candidate)
    absolute = _normalise(absolute)
    relative = _normalise(relative)
    return (
        candidate == absolute
        or candidate.endswith("/" + relative)
        or absolute.endswith("/" + candidate)
    )


def _target_entry(files, absolute, relative):
    for key in files:
        if _matches(key, absolute, relative):
            return key
    return relative


def _source_candidates(files, absolute, relative):
    candidates = [absolute]
    rendered_roots = os.environ.get(%r, "")
    for root in rendered_roots.split(os.pathsep):
        root = root.strip()
        if root:
            candidates.append(os.path.join(root, relative))
    for key in files:
        if _matches(key, absolute, relative):
            candidates.append(key)
    unique = []
    seen = set()
    for candidate in candidates:
        rendered = _normalise(candidate)
        if rendered in seen:
            continue
        seen.add(rendered)
        unique.append(candidate)
    return unique


def _resolve_source(files, absolute, relative):
    for candidate in _source_candidates(files, absolute, relative):
        rendered = os.path.abspath(candidate)
        if os.path.isfile(rendered):
            return rendered
    return absolute


def main():
    manifest_path = os.environ["TESTPRISM_COVERAGE_TARGETS"]
    report_path = os.environ["TESTPRISM_COVERAGE_JSON"]
    config_path = os.environ["TESTPRISM_COVERAGE_CONFIG"]
    data_path = os.environ["COVERAGE_FILE"]
    with open(manifest_path, "r") as manifest_file:
        targets = json.load(manifest_file)
    with open(report_path, "r") as report_file:
        report = json.load(report_file)
    files = report.get("files")
    if not isinstance(files, dict):
        raise ValueError("coverage report is missing a files object")

    measured = coverage.Coverage(
        data_file=data_path,
        config_file=config_path,
    )
    measured.load()
    for target in targets:
        absolute = target["absolute"]
        relative = target["relative"]
        source_path = _resolve_source(files, absolute, relative)
        try:
            filename, statements, _excluded, _missing, _formatted = (
                measured.analysis2(source_path)
            )
            statements = set(int(line) for line in statements if int(line) > 0)
        except coverage.exceptions.NoSource:
            filename = source_path
            statements = set()
        key = _target_entry(files, filename, relative)
        entry = files.get(key, {})
        if not isinstance(entry, dict):
            entry = {}
        executed = _lines(entry.get("executed_lines"))
        if not statements:
            # Keep a measured report's existing information if a source parser
            # cannot identify statements (for example a generated file).
            statements = executed | _lines(entry.get("missing_lines"))
        entry["executed_lines"] = sorted(executed & statements)
        entry["missing_lines"] = sorted(statements - executed)
        summary = entry.get("summary")
        if not isinstance(summary, dict):
            summary = {}
        summary["covered_lines"] = len(entry["executed_lines"])
        summary["num_statements"] = len(statements)
        summary["missing_lines"] = len(entry["missing_lines"])
        summary["percent_covered"] = (
            100.0 * len(entry["executed_lines"]) / len(statements)
            if statements
            else 100.0
        )
        entry["summary"] = summary
        files[key] = entry

    report["files"] = files
    total_covered = 0
    total_missing = 0
    total_statements = 0
    total_excluded = 0
    for entry in files.values():
        if not isinstance(entry, dict):
            continue
        executed = _lines(entry.get("executed_lines"))
        missing = _lines(entry.get("missing_lines"))
        excluded = _lines(entry.get("excluded_lines"))
        total_covered += len(executed)
        total_missing += len(missing)
        total_statements += len(executed | missing)
        total_excluded += len(excluded)
    totals = report.get("totals")
    if not isinstance(totals, dict):
        totals = {}
    totals["covered_lines"] = total_covered
    totals["missing_lines"] = total_missing
    totals["num_statements"] = total_statements
    totals["excluded_lines"] = total_excluded
    totals["percent_covered"] = (
        100.0 * total_covered / total_statements if total_statements else 100.0
    )
    report["totals"] = totals
    with open(report_path, "w") as report_file:
        json.dump(report, report_file)


if __name__ == "__main__":
    main()
'''
    % TESTPRISM_COVERAGE_SOURCE_ROOTS
)


@dataclass(frozen=True)
class CoverageRuntimeFiles:
    """Host-side files copied into a disposable evaluation container."""

    root: Path
    sitecustomize_path: Path
    config_path: Path
    # Container-side namespace paths.  Keeping these with the copied files
    # prevents the orchestration layer from accidentally combining suites.
    namespace: str | None = None
    container_root: str = COVERAGE_ROOT
    bootstrap_dir: str = COVERAGE_BOOTSTRAP_DIR
    data_dir: str = COVERAGE_DATA_DIR
    json_path: str = COVERAGE_JSON_PATH
    targets_path: str = f"{COVERAGE_ROOT}/targets.json"
    finalize_path: str = f"{COVERAGE_ROOT}/finalize_coverage.py"


@dataclass(frozen=True)
class CoverageNamespace:
    """Container paths for one physically isolated coverage suite."""

    name: str | None
    root: str
    bootstrap_dir: str
    data_dir: str
    config_path: str
    json_path: str
    targets_path: str
    finalize_path: str


_NAMESPACE_RE = re.compile(r"^[A-Za-z0-9_-]+$")


def coverage_namespace(namespace: str | None = None) -> CoverageNamespace:
    """Return paths for ``namespace`` without allowing path traversal.

    ``None`` denotes the historical unsuffixed runtime.  New orchestration
    code must use explicit names so generated and trusted reference reports
    cannot share a data/config/output path.
    """

    if namespace is None:
        root = COVERAGE_ROOT
    else:
        if not _NAMESPACE_RE.fullmatch(namespace):
            raise ValueError(f"invalid coverage namespace: {namespace!r}")
        root = f"{COVERAGE_ROOT}/{namespace}"
    return CoverageNamespace(
        name=namespace,
        root=root,
        bootstrap_dir=f"{root}/bootstrap",
        data_dir=f"{root}/data",
        config_path=f"{root}/coveragerc",
        json_path=f"{root}/coverage.json",
        targets_path=f"{root}/targets.json",
        finalize_path=f"{root}/finalize_coverage.py",
    )


def _absolute_target(workdir: str, relative_path: str) -> str:
    workdir_path = PurePosixPath(workdir)
    candidate = PurePosixPath(relative_path)
    if candidate.is_absolute():
        try:
            candidate = candidate.relative_to(workdir_path)
        except ValueError as exc:
            raise ValueError(
                f"coverage target escapes workdir: {relative_path}"
            ) from exc
    if ".." in candidate.parts:
        raise ValueError(f"coverage target escapes workdir: {relative_path}")
    return str(workdir_path / candidate)


def write_runtime_files(
    root: Path,
    *,
    workdir: str,
    target_paths: list[str],
    namespace: str | None = None,
) -> CoverageRuntimeFiles:
    """Create sitecustomize/configuration for one isolated coverage suite."""

    if not target_paths:
        raise ValueError("coverage runtime requires at least one target path")
    paths = coverage_namespace(namespace)
    root.mkdir(parents=True, exist_ok=True)
    bootstrap = root / "bootstrap"
    bootstrap.mkdir(parents=True, exist_ok=True)
    sitecustomize = bootstrap / "sitecustomize.py"
    sitecustomize.write_text(SITECUSTOMIZE_SOURCE)
    hook_module = bootstrap / f"{TESTPRISM_COVERAGE_BOOTSTRAP_MODULE}.py"
    hook_module.write_text(BOOTSTRAP_HOOK_SOURCE)
    hook_pth = bootstrap / TESTPRISM_COVERAGE_BOOTSTRAP_PTH
    hook_pth.write_text(BOOTSTRAP_HOOK_PTH_SOURCE)
    fallback_root = bootstrap / VENDORED_COVERAGE_ROOT_NAME
    fallback_root.mkdir(parents=True, exist_ok=True)
    shutil.copytree(VENDORED_COVERAGE_PACKAGE, fallback_root / "coverage")

    absolute_targets = sorted(
        {_absolute_target(workdir, path) for path in target_paths}
    )
    workdir_path = PurePosixPath(workdir)
    targets = [
        f"*/{PurePosixPath(path).relative_to(workdir_path)}"
        for path in absolute_targets
    ]
    parser = configparser.ConfigParser()
    parser["run"] = {
        "branch": "False",
        "parallel": "True",
        "data_file": f"{paths.data_dir}/.coverage",
        "include": "\n".join(targets),
        "omit": f"{workdir.rstrip('/')}/agent-tests/*",
    }
    parser["report"] = {"ignore_errors": "True"}
    config = root / "coveragerc"
    with config.open("w") as file:
        parser.write(file)
    target_manifest = root / "targets.json"
    target_manifest.write_text(
        json.dumps(
            [
                {
                    "absolute": absolute,
                    "relative": PurePosixPath(absolute)
                    .relative_to(workdir_path)
                    .as_posix(),
                }
                for absolute in absolute_targets
            ]
        )
    )
    finalize_path = root / "finalize_coverage.py"
    finalize_path.write_text(COVERAGE_FINALIZE_SOURCE)
    return CoverageRuntimeFiles(
        root=root,
        sitecustomize_path=sitecustomize,
        config_path=config,
        namespace=namespace,
        container_root=paths.root,
        bootstrap_dir=paths.bootstrap_dir,
        data_dir=paths.data_dir,
        json_path=paths.json_path,
        targets_path=paths.targets_path,
        finalize_path=paths.finalize_path,
    )


def coverage_setup_command(namespace: str | None = None) -> str:
    """Return a fail-soft command that verifies the injected offline runtime."""

    paths = coverage_namespace(namespace)
    return (
        f"mkdir -p {paths.root} {paths.data_dir} {paths.bootstrap_dir} && "
        "__ctb_py=$(command -v python3 || command -v python); "
        'if [ -z "$__ctb_py" ]; then echo __TESTPRISM_COVERAGE_SETUP__=no_python; '
        "elif \"$__ctb_py\" >/dev/null 2>&1 <<'PY'\n"
        "from __future__ import print_function\n"
        "import json\n"
        "import os\n"
        "import shutil\n"
        "import site\n"
        "import sysconfig\n"
        "\n"
        f"bootstrap_dir = {paths.bootstrap_dir!r}\n"
        f"root = {paths.root!r}\n"
        f"config_path = {paths.config_path!r}\n"
        f"data_file = {f'{paths.data_dir}/.coverage'!r}\n"
        f"state_path = {COVERAGE_ACTIVE_BOOTSTRAP_PATH!r}\n"
        f"module_name = {TESTPRISM_COVERAGE_BOOTSTRAP_MODULE!r}\n"
        f"pth_name = {TESTPRISM_COVERAGE_BOOTSTRAP_PTH!r}\n"
        f"override_env = {TESTPRISM_COVERAGE_SITE_DIR!r}\n"
        "candidates = []\n"
        "override = os.environ.get(override_env)\n"
        "if override:\n"
        "    candidates.extend(item for item in override.split(os.pathsep) if item)\n"
        "else:\n"
        "    getter = getattr(site, 'getsitepackages', None)\n"
        "    if getter is not None:\n"
        "        try:\n"
        "            candidates.extend(getter())\n"
        "        except Exception:\n"
        "            pass\n"
        "    user_site = getattr(site, 'getusersitepackages', lambda: None)()\n"
        "    if user_site:\n"
        "        candidates.append(user_site)\n"
        "    for key in ('purelib', 'platlib'):\n"
        "        try:\n"
        "            candidate = sysconfig.get_path(key)\n"
        "        except Exception:\n"
        "            candidate = None\n"
        "        if candidate:\n"
        "            candidates.append(candidate)\n"
        "site_dirs = []\n"
        "for candidate in candidates:\n"
        "    rendered = os.path.abspath(candidate)\n"
        "    if rendered not in site_dirs:\n"
        "        site_dirs.append(rendered)\n"
        "for site_dir in site_dirs:\n"
        "    try:\n"
        "        if not os.path.isdir(site_dir):\n"
        "            os.makedirs(site_dir)\n"
        "    except Exception:\n"
        "        pass\n"
        "    for stale in (module_name + '.py', pth_name):\n"
        "        stale_path = os.path.join(site_dir, stale)\n"
        "        try:\n"
        "            if os.path.exists(stale_path):\n"
        "                os.remove(stale_path)\n"
        "        except Exception:\n"
        "            pass\n"
        "source_module = os.path.join(bootstrap_dir, module_name + '.py')\n"
        "source_pth = os.path.join(bootstrap_dir, pth_name)\n"
        "installed = False\n"
        "for site_dir in site_dirs:\n"
        "    try:\n"
        "        shutil.copy2(\n"
        "            source_module, os.path.join(site_dir, module_name + '.py')\n"
        "        )\n"
        "        shutil.copy2(source_pth, os.path.join(site_dir, pth_name))\n"
        "        installed = True\n"
        "        break\n"
        "    except Exception:\n"
        "        continue\n"
        "if not installed:\n"
        "    raise SystemExit(1)\n"
        "with open(state_path, 'w') as state_file:\n"
        "    json.dump(\n"
        "        {\n"
        "            'namespace': os.path.basename(root),\n"
        "            'bootstrap_dir': bootstrap_dir,\n"
        "            'config_path': config_path,\n"
        "            'data_file': data_file,\n"
        "        },\n"
        "        state_file,\n"
        "    )\n"
        "PY\n"
        "then "
        "echo __TESTPRISM_COVERAGE_SETUP__=ready; "
        "else echo __TESTPRISM_COVERAGE_SETUP__=unsupported; fi"
    )


def coverage_environment(
    workdir: str,
    namespace: str | None = None,
) -> dict[str, str]:
    """Environment injected while the agent-owned shell runner executes."""

    del workdir
    del namespace
    return {}


def coverage_collect_command(namespace: str | None = None) -> str:
    """Combine process data and write a coverage.py JSON report."""

    paths = coverage_namespace(namespace)
    source_roots_default = "$PWD:/app:/testbed:/workspace:/workspace/default"
    return (
        "__ctb_py=$(command -v python3 || command -v python); "
        f"export {TESTPRISM_COVERAGE_DISABLE_AUTO_START}=1; "
        f'export {TESTPRISM_COVERAGE_SOURCE_ROOTS}="'
        f'${{{TESTPRISM_COVERAGE_SOURCE_ROOTS}'
        f':-{source_roots_default}}}"; '
        "unset COVERAGE_PROCESS_START; "
        f"export PYTHONPATH={paths.bootstrap_dir}; "
        f"export COVERAGE_FILE={paths.data_dir}/.coverage; "
        f"export COVERAGE_RCFILE={paths.config_path}; "
        'if [ -z "$__ctb_py" ] || ! "$__ctb_py" -c \'import coverage\' '
        ">/dev/null 2>&1; then echo __TESTPRISM_COVERAGE_COLLECT__=unsupported; "
        f'elif ("$__ctb_py" -m coverage combine --keep {paths.data_dir} '
        ">/dev/null 2>&1 || "
        f'! find {paths.data_dir} -maxdepth 1 -type f -name ".coverage*" '
        "-print -quit 2>/dev/null | grep -q .) && ( "
        f'if "$__ctb_py" -m coverage json -o {paths.json_path} '
        ">/dev/null 2>&1; then :; "
        f'elif [ ! -e {paths.json_path} ]; then '
        f"printf '{{\"files\":{{}},\"totals\":{{}}}}\\n' > {paths.json_path}; "
        "else exit 1; fi; "
        f"export TESTPRISM_COVERAGE_TARGETS={paths.targets_path}; "
        f"export TESTPRISM_COVERAGE_JSON={paths.json_path}; "
        f"export TESTPRISM_COVERAGE_CONFIG={paths.config_path}; "
        f'"$__ctb_py" {paths.finalize_path} >/dev/null 2>&1 ) ; then '
        "echo __TESTPRISM_COVERAGE_COLLECT__=collected; "
        "else echo __TESTPRISM_COVERAGE_COLLECT__=failed; fi"
    )
